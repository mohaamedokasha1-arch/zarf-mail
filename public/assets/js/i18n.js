  /* ============================= 3) المحرك ============================= */
  let current = 'ar';
  const listeners = [];

  /** اتجاه اللغة */
  function dirOf(code) {
    const lang = LANGS.find((l) => l.code === code);
    if (lang) return lang.dir;
    return RTL_LOCALES.includes(String(code).split('-')[0]) ? 'rtl' : 'ltr';
  }

  /** استبدال المتغيرات {name} في النص */
  function interpolate(text, vars) {
    if (!vars) return text;
    return String(text).replace(/\{(\w+)\}/g, (match, key) => (
      Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : match
    ));
  }

  /**
   * ترجمة مفتاح
   * @param {string} key
   * @param {object} [vars] متغيرات مثل {count: 3}
   */
  function t(key, vars) {
    const table = DICT[current] || {};
    let value = table[key];
    if (value === undefined) value = (DICT[FALLBACK] || {})[key];
    if (value === undefined) return key;
    return interpolate(value, vars);
  }

  /** تصنيف الجمع حسب اللغة والعدد */
  function pluralKey(count) {
    const n = Math.abs(Number(count) || 0);
    const mod100 = n % 100;

    if (current === 'ar') {
      if (n === 0) return 'zero';
      if (n === 1) return 'one';
      if (n === 2) return 'two';
      if (mod100 >= 3 && mod100 <= 10) return 'few';
      if (mod100 >= 11 && mod100 <= 99) return 'many';
      return 'other';
    }
    if (current === 'ru') {
      const mod10 = n % 10;
      if (mod10 === 1 && mod100 !== 11) return 'one';
      if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 'few';
      return 'many';
    }
    if (current === 'pl') {
      const mod10 = n % 10;
      if (n === 1) return 'one';
      if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 'few';
      if (mod10 === 0 || mod10 === 1 || (mod10 >= 5 && mod10 <= 9) || (mod100 >= 12 && mod100 <= 14)) return 'many';
      return 'other';
    }
    // بقية اللغات: واحد / أخرى
    if (n === 1) return 'one';
    if (n === 2 && (DICT[current] || {})['inbox.count_two']) return 'two';
    return 'other';
  }

  /** ترجمة نص بصيغة الجمع: tCount('inbox.count', 5) */
  function tCount(baseKey, count) {
    const suffix = pluralKey(count);
    const table = DICT[current] || {};
    if (table[`${baseKey}_${suffix}`] !== undefined) {
      return t(`${baseKey}_${suffix}`, { count });
    }
    if ((DICT[FALLBACK] || {})[`${baseKey}_${suffix}`] !== undefined) {
      return t(`${baseKey}_${suffix}`, { count });
    }
    return t(`${baseKey}_other`, { count });
  }

  /** تطبيق الترجمات على عناصر DOM التي تحمل data-i18n */
  function applyDocument(root = (typeof document !== 'undefined' ? document : null)) {
    if (!root) return;
    const nodes = root.querySelectorAll('[data-i18n], [data-i18n-placeholder], [data-i18n-title], [data-i18n-aria], [data-i18n-html]');
    nodes.forEach((el) => {
      if (el.dataset.i18n) el.textContent = t(el.dataset.i18n);
      if (el.dataset.i18nHtml) el.innerHTML = t(el.dataset.i18nHtml);
      if (el.dataset.i18nPlaceholder) el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
      if (el.dataset.i18nTitle) el.setAttribute('title', t(el.dataset.i18nTitle));
      if (el.dataset.i18nAria) el.setAttribute('aria-label', t(el.dataset.i18nAria));
    });

    // عنوان الصفحة ووصفها
    const titleEl = document.querySelector('[data-i18n-title-doc]');
    if (titleEl) document.title = t(titleEl.dataset.i18nTitleDoc);
    const descEl = document.querySelector('meta[name="description"]');
    if (descEl) descEl.setAttribute('content', t('meta.desc'));
  }

  /**
   * تغيير اللغة فوراً (بدون إعادة تحميل)
   * @param {string} code
   */
  function setLocale(code, { silent = false } = {}) {
    const lang = LANGS.find((l) => l.code === code);
    if (!lang) return current;

    current = code;

    // تحديث اتجاه الصفحة (RTL للعربية والفارسية — LTR لبقية اللغات)
    if (typeof document !== 'undefined') {
      const html = document.documentElement;
      html.setAttribute('lang', code);
      html.setAttribute('dir', lang.dir);
    }

    try { if (typeof localStorage !== 'undefined') localStorage.setItem(STORAGE_KEY, code); } catch (e) { /* تجاهل */ }

    applyDocument();

    if (!silent) {
      listeners.forEach((fn) => {
        try { fn(code, lang); } catch (e) { /* تجاهل */ }
      });
      if (typeof document !== 'undefined' && typeof CustomEvent === 'function') {
        document.dispatchEvent(new CustomEvent('zarf:localechange', { detail: { code, lang } }));
      }
    }
    return code;
  }

  /** اللغة الحالية */
  const getLocale = () => current;
  /** بيانات اللغة الحالية */
  const getCurrentLang = () => LANGS.find((l) => l.code === current) || LANGS[0];
  /** تسجيل مستمع لتغيّر اللغة */
  function onChange(fn) { listeners.push(fn); }

  /** كشف اللغة الأولى: المحفوظة → لغة المتصفح → العربية */
  function detectLocale() {
    let saved = null;
    try { saved = (typeof localStorage !== 'undefined') ? localStorage.getItem(STORAGE_KEY) : null; } catch (e) { /* تجاهل */ }
    if (saved && LANGS.some((l) => l.code === saved)) return saved;

    const hasNav = typeof navigator !== 'undefined';
    const nav = (hasNav && navigator.languages && navigator.languages.length)
      ? navigator.languages
      : (hasNav ? [navigator.language || 'ar'] : []);

    for (const tag of nav) {
      const short = String(tag).toLowerCase().split('-')[0];
      if (LANGS.some((l) => l.code === short)) return short;
    }
    return 'ar';
  }

  /** تهيئة: تُستدعى عند تحميل الصفحة */
  function init() {
    setLocale(detectLocale(), { silent: true });
    return current;
  }

  const api = { LANGS, DICT, t, tCount, setLocale, getLocale, getCurrentLang, dirOf, onChange, applyDocument, init, detectLocale };

  global.ZarfI18n = api;
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
